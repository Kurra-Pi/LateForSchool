CREATE TABLE SCHOOL_PLAYERS (
    PLAYER_KEY VARCHAR2(240 CHAR) PRIMARY KEY,
    DISPLAY_NAME VARCHAR2(60 CHAR) NOT NULL,

    BEST_SCORE NUMBER(10),
    BEST_TIME_MS NUMBER(15),

    TOTAL_CANDIES NUMBER(10) DEFAULT 0 NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT CK_SCHOOL_PLAYERS_RUN CHECK (
        (BEST_SCORE IS NULL AND BEST_TIME_MS IS NULL)
        OR
        (
            BEST_SCORE IS NOT NULL
            AND BEST_TIME_MS IS NOT NULL
            AND BEST_SCORE >= 0
            AND BEST_TIME_MS >= 0
        )
    ),

    CONSTRAINT CK_SCHOOL_PLAYERS_CANDY CHECK (
        TOTAL_CANDIES >= 0
    )
);

SELECT * FROM SCHOOL_PLAYERS;